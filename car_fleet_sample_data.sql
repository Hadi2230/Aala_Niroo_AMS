    SELECT MAX(cfr.mileage_at_fuel) 
    FROM car_fuel_records cfr 
    WHERE cfr.car_id = cc.id
) 
WHERE EXISTS (
    SELECT 1 FROM car_fuel_records cfr WHERE cfr.car_id = cc.id
);

